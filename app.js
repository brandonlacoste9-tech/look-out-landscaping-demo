function applyLang(l) {
  lang = l;
  localStorage.setItem("vf-lang", l);
  document.documentElement.lang = l;
  document.querySelectorResidential("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = I18N[l][key];
    if (val !== undefined) el.innerHTML = val;
  });
  document.getElementById("langToggle").textContent = l === "fr" ? "EN" : "FR";
  document.title = l === "fr"
    ? "Look Out Landscaping Ltd — Aménagement paysager et déneigement à Kamloops | Maquette gratuite"
    : "Look Out Landscaping Ltd — Landscaping & Snow Removal in Kamloops | Free Mockup";
}

